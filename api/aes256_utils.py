hw_table = np.array([bin(i).count('1') for i in range(256)], dtype=np.uint8)

# ShiftRows 置換索引（AES column-major 排列）
# Row 0 (bytes 0,4,8,12):  不移動
# Row 1 (bytes 1,5,9,13):  左移 1
# Row 2 (bytes 2,6,10,14): 左移 2
# Row 3 (bytes 3,7,11,15): 左移 3
SR_PERM = np.array([0, 5, 10, 15, 4, 9, 14, 3, 8, 13, 2, 7, 12, 1, 6, 11], dtype=np.int32)


def _xtime(a: np.ndarray) -> np.ndarray:
    """GF(2^8) 乘以 2，批次處理。a shape: (...,)"""
    a = a.astype(np.uint16)
    return np.where(a & 0x80, ((a << 1) ^ 0x1B) & 0xFF, (a << 1) & 0xFF).astype(np.uint8)


def batch_mix_columns(states: np.ndarray) -> np.ndarray:
    """
    對 (N, 16) 的 AES state 批次套用 MixColumns。
    AES column-major：column j = bytes [j*4, j*4+1, j*4+2, j*4+3]
    """
    result = np.empty_like(states, dtype=np.uint8)
    for col in range(4):
        idx = col * 4
        a0 = states[:, idx    ]
        a1 = states[:, idx + 1]
        a2 = states[:, idx + 2]
        a3 = states[:, idx + 3]
        x0, x1, x2, x3 = _xtime(a0), _xtime(a1), _xtime(a2), _xtime(a3)
        result[:, idx    ] = x0 ^ x1 ^ a1 ^ a2 ^ a3
        result[:, idx + 1] = a0 ^ x1 ^ x2 ^ a2 ^ a3
        result[:, idx + 2] = a0 ^ a1 ^ x2 ^ x3 ^ a3
        result[:, idx + 3] = x0 ^ a0 ^ a1 ^ a2 ^ x3
    return result


def compute_state_before_rk1(plaintexts: np.ndarray, key0: np.ndarray) -> np.ndarray:
    """
    計算 Phase 2 攻擊所需的中間狀態。

    state_before_RK1 = MixColumns(ShiftRows(SubBytes(plaintext XOR key[0:15])))

    參數
    ----
    plaintexts : (N, 16) uint8
    key0       : (16,)  uint8 — Phase 1 回復的 key[0:15]

    回傳
    ----
    (N, 16) uint8 — 每條 trace 的 state，就在 AddRoundKey(RK1) 之前
    """
    plaintexts = np.asarray(plaintexts, dtype=np.uint8)
    key0 = np.asarray(key0, dtype=np.uint8)
    if plaintexts.ndim != 2 or plaintexts.shape[1] != 16:
        raise ValueError(f"plaintexts 必須是 (N, 16)，目前為 {plaintexts.shape}")
    if key0.ndim == 1 and key0.shape == (16,):
        round_key = key0[np.newaxis, :]
    elif key0.ndim == 2 and key0.shape == plaintexts.shape:
        round_key = key0
    else:
        raise ValueError(
            f"key0 必須是 (16,) 或與 plaintexts 相同的 (N, 16)，目前為 {key0.shape}"
        )
    state = plaintexts ^ round_key  # AddRoundKey 0
    state = AES_Sbox[state]                                                       # SubBytes
    state = state[:, SR_PERM]                                                     # ShiftRows
    state = batch_mix_columns(state)                                              # MixColumns
    return state
